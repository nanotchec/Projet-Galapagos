def make_clean_zip(*, version: str, dry_run: bool = False, root: Path | None = None) -> dict:
    version = normalize_version(version)
    root = (root or Path.cwd()).resolve()
    if version in {"v1_98_2", "v1_99"}:
        return _make_minimal_audit_zip(version=version, dry_run=dry_run, root=root)
    zip_name = f"projet-galapagos-{version.replace('_', '.')}-clean.zip"
    zip_path = root / zip_name
    included = []
    excluded = []
    for path in sorted(root.rglob("*")):
        if path == zip_path or path.is_dir():
            continue
        relative = path.relative_to(root)
        if _excluded(relative, version):
            excluded.append(str(relative))
            continue
        included.append(str(relative))
    if not dry_run:
        with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for item in included:
                archive.write(root / item, item)
    forbidden_entries = [item for item in included if _forbidden_in_zip(Path(item), version)]
    return {
        "version": version,
        "zip_path": str(zip_path),
        "dry_run": dry_run,
        "included_count": len(included),
        "excluded_count": len(excluded),
        "included_preview": included[:50],
        "excluded_preview": excluded[:50],
        "missing_required_files": _missing_required_files(included, version),
        "forbidden_entries": forbidden_entries,
        "zip_written": not dry_run,
    }


def _make_minimal_audit_zip(*, version: str, dry_run: bool, root: Path) -> dict:
    zip_name = f"projet-galapagos-{version.replace('_', '.')}-clean.zip"
    zip_path = root / zip_name
    included: list[str] = []
    excluded: list[str] = []
    for path in sorted(root.rglob("*")):
        if path == zip_path or path.is_dir():
            continue
        relative = path.relative_to(root)
        if _minimal_audit_included(relative, version):
            included.append(str(relative))
        else:
            excluded.append(str(relative))
    if not dry_run:
        with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for item in included:
                archive.write(root / item, item)
    forbidden_entries = [item for item in included if _forbidden_in_zip(Path(item), version)]
    historical_report_versions = set()
    for item in excluded:
        if item.startswith("reports/research/") or item.startswith("reports/release_zip_") or item.startswith("reports/zip_audit_") or item.startswith("reports/zip_smoke_test_"):
            match = re.search(r"v1(?:_|\d|\\.)+", item)
            if match:
                historical_report_versions.add(match.group(0))
    return {
        "version": version,
        "zip_path": str(zip_path),
        "dry_run": dry_run,
        "included_count": len(included),
        "excluded_count": len(excluded),
        "included_preview": included[:50],
        "excluded_preview": excluded[:50],
        "missing_required_files": _missing_required_files(included, version),
        "forbidden_entries": forbidden_entries,
        "zip_written": not dry_run,
        "minimal_audit_zip": True,
        "historical_reports_pruned_from_zip": True,
        "required_source_versions_included": ["V1.92.1", "V1.95.1", "V1.97.2", "V1.98.2"] + (["V1.99"] if version == "v1_99" else []),
        "excluded_historical_versions_count": len(historical_report_versions),
        "zip_size_bytes": zip_path.stat().st_size if zip_path.exists() and not dry_run else 0,
        "zip_size_reduction_applied": True,
    }


def _minimal_audit_included(relative: Path, version: str) -> bool:
    if any(part in EXCLUDED_DIRS or part.startswith("temp_extract_") for part in relative.parts):
        return False
    if fnmatch.fnmatch(relative.name, "*.zip") or relative.name in {".DS_Store"}:
        return False
    if relative.suffix in {".parquet", ".csv", ".sqlite", ".jsonl", ".db"}:
        return False
    if relative.parts and relative.parts[0] in {"src", "scripts", "tests"}:
        return True
    if str(relative) in {"pyproject.toml", "pytest.ini", "requirements.txt", "AGENTS.md", "README.md"}:
        return True
    rel_s = str(relative)
    if relative.parts[:2] == ("reports", "current"):
        return True
    if rel_s in {
        "reports/PROJECT_STATE.json",
        "reports/PROJECT_STATE.md",
        "reports/REPORT_INDEX.md",
    }:
        return True
    if relative.parts[:2] == ("reports", "research"):
        tokens = ("v1_99", "v1_98_2", "v1_97_2", "v1_95_1", "v1_92_1") if version == "v1_99" else ("v1_98_2", "v1_97_2", "v1_95_1", "v1_92_1")
        return any(token in relative.name for token in tokens)
    if relative.parts and relative.parts[0] == "reports":
        if version == "v1_99":
            return relative.name in {
                "release_zip_v1_99.json",
                "release_zip_v1_99.md",
                "zip_audit_v1_99.json",
                "zip_audit_v1_99.md",
                "zip_smoke_test_v1_99.json",
                "zip_smoke_test_v1_99.md",
            }
        return relative.name in {
            "release_zip_v1_98_2.json",
            "release_zip_v1_98_2.md",
            "zip_audit_v1_98_2.json",
            "zip_audit_v1_98_2.md",
            "zip_smoke_test_v1_98_2.json",
            "zip_smoke_test_v1_98_2.md",
        }
    if relative.parts and relative.parts[0] == "docs":
        return version in relative.name
    if relative.parts[:4] == ("data", "research", "dataset_seed", "v1_92"):
        return True
    if relative.parts[:4] == ("data", "research", "feature_preview", "v1_95"):
        return True
    if relative.parts[:4] == ("data", "research", "label_preview", "v1_97"):
        return True
    if version == "v1_99" and relative.parts[:4] == ("data", "research", "training_dataset_preview", "v1_99"):
        return True
    return False


